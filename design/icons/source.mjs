const ring = (cx, cy, r) => `M${cx + r} ${cy}A${r} ${r} 0 1 1 ${cx - r} ${cy}A${r} ${r} 0 1 1 ${cx + r} ${cy}Z`;
const rays = (cx, cy, r1, r2, n, from = 0) => Array.from({ length: n }, (_, k) => {
  const a = (from + (k * 360) / n) * Math.PI / 180;
  const f = (v) => v.toFixed(2);
  return `M${f(cx + Math.cos(a) * r1)} ${f(cy + Math.sin(a) * r1)}L${f(cx + Math.cos(a) * r2)} ${f(cy + Math.sin(a) * r2)}`;
}).join('');

// A gear outline: n square teeth between radius r1 and r2.
const gear = (cx, cy, r1, r2, n) => {
  const f = (v) => v.toFixed(2);
  const pt = (deg, r) => { const a = deg * Math.PI / 180; return `${f(cx + Math.cos(a) * r)} ${f(cy + Math.sin(a) * r)}`; };
  let d = '';
  for (let k = 0; k < n; k++) {
    const t = (k * 360) / n - 90, w = 360 / n;
    d += `${k ? 'L' : 'M'}${pt(t - w * 0.28, r1)}L${pt(t - w * 0.17, r2)}L${pt(t + w * 0.17, r2)}L${pt(t + w * 0.28, r1)}`;
  }
  return d + 'Z';
};

